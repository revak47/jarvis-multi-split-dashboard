const fs=require('fs'),vm=require('vm'),assert=require('assert'),path=require('path');
const root=path.resolve(__dirname,'..');
const manifest=JSON.parse(fs.readFileSync(path.join(root,'manifest.json'),'utf8').replace(/^\uFEFF/,''));
assert(!manifest.host_permissions,'no broad hosts');
assert(!manifest.declarative_net_request,'no header overrides');
assert(!manifest.permissions.includes('cookies'),'no cookie access');
const sent=[],opened=[],listeners={};
const chrome={runtime:{getURL:s=>'chrome-extension://test/'+s,onMessage:{addListener:f=>listeners.message=f}},tabs:{create:({url})=>opened.push(url),query:(q,cb)=>cb([{id:11}]),sendMessage:(id,msg)=>{sent.push({id,msg});return Promise.resolve()}},commands:{onCommand:{addListener:f=>listeners.command=f}}};
vm.runInNewContext(fs.readFileSync(path.join(root,'background.js'),'utf8'),{chrome,console});
assert.equal(typeof listeners.message,'function');
let response;listeners.message({action:'open_dashboard'},null,x=>response=x);
assert.equal(opened[0],'chrome-extension://test/dashboard.html');assert.equal(response.status,'ok');
listeners.message({type:'DISPARAR_PROMPT_IA',text:'test'},null,x=>response=x);
assert.equal(sent.length,1);assert.equal(sent[0].id,11);
assert.equal(response.dispatched,true);
const dashboard=fs.readFileSync(path.join(root,'dashboard.js'),'utf8');
assert(!dashboard.includes('fix_cookies'),'dashboard cannot request cookie modifications');
assert(dashboard.includes('const browser = typeof globalThis.browser'),'chrome fallback');
console.log('PASS manifest restrictions, dashboard opening, AI dispatch, Chrome compatibility, no cookie request');
